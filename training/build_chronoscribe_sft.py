#!/usr/bin/env python3
"""Convert ordinary CSV time series into ChronoScribe SFT records.

The converter builds supervision for the language controller only.  It never
asks the controller to predict a future numerical trajectory.  Each valid
history window yields two linked chat records:

* ``directive_generation``: request plus a history summary -> executable
  ``use_chronos2``, ``prediction_length``, and ``context_length`` JSON.
* ``evidence_conditioned_response``: request plus deterministic forecast
  evidence -> a grounded JSON response.

The response evidence is obtained from a deterministic seasonal-naive proxy
unless externally generated specialist quantiles are supplied.  Proxy records
are structurally valid supervision for the response interface, but should not
be described as outputs of Chronos-2.  To reproduce an adapter that was
trained on specialist evidence, provide records generated by that specialist.

All executable identifiers and prompt contracts intentionally match the
reference ChronoScribe runner.  The user-facing task prompts are Chinese
because the released reference controller and benchmark use Chinese prompts;
code, metadata, and documentation remain English.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import random
import re
from dataclasses import dataclass
from pathlib import Path
from statistics import mean, pstdev
from typing import Iterable, Iterator, Mapping, Sequence


# These two system prompts are byte-for-byte compatible with the strings in
# runners/run_chronoscribe.py.  Do not translate or simplify them without also
# changing the inference runner and retraining the adapter.
ROUTER_SYSTEM_PROMPT = (
    "只outputJSON。判断是否需要time series forecasting：\n"
    "有historical data+预测需求 → {\"use_chronos2\":true,\"prediction_length\":int,\"context_length\":int}\n"
    "普通对话/无数据 → {\"use_chronos2\":false,\"direct_reply\":\"简短直接回复\"}\n"
    "禁止outputJSON之外的任何Text、思考过程或解释。"
)

RESPONSE_SYSTEM_PROMPT = (
    "你是time series forecasting分析专家。将forecast results转化为natural language解读。"
    "JSON:{\"trend\":\"...\",\"analysis\":\"...\"}"
)

TIMESTAMP_CANDIDATES = {
    "date",
    "datetime",
    "ds",
    "time",
    "timestamp",
    "timestamp_(min)",
}

